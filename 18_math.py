import math

# find the square root of a number
print(math.sqrt(64))

# find the power of a number
print(math.pow(2, 3))

# floor
print(math.floor(7.92))
print(math.floor(5.36))

# ceil
print(math.ceil(7.92))
print(math.ceil(5.36))

# trunc
print(math.trunc(78.1253))

# factorial
print(math.factorial(5))
print(math.factorial(10))

# isnan => not a number
print(math.isnan(15))
print(math.isnan(float("naan")))

# gcd - greatest common divisor (HCF)
print(math.gcd(48, 96))

# lcm - lowest common multiple
print(math.lcm(12, 36, 48))